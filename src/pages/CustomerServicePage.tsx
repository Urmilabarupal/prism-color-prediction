import React, { useEffect, useState } from 'react';
import {
  Headphones,
  MessageSquare,
  Send,
  HelpCircle,
  Mail,
  ChevronRight,
  ChevronDown,
  X,
  MessageCircle,
} from 'lucide-react';
import { PageId, SupportTicket } from '../types.js';
import { useAuth } from '../context/AuthContext.js';
import { api } from '../services/api.js';
import { TopHeader } from '../components/TopHeader.js';

interface CustomerServicePageProps {
  onNavigate: (page: PageId) => void;
}

export const CustomerServicePage: React.FC<CustomerServicePageProps> = ({ onNavigate }) => {
  const { user } = useAuth();
  const [activeFaq, setActiveFaq] = useState<number | null>(null);
  const [showLiveChat, setShowLiveChat] = useState<boolean>(false);
  const [messages, setMessages] = useState<SupportTicket[]>([]);
  const [inputMsg, setInputMsg] = useState<string>('');
  const [sending, setSending] = useState<boolean>(false);

  useEffect(() => {
    if (user && showLiveChat) {
      api.getSupportMessages(user.id).then(setMessages).catch(console.error);
    }
  }, [user?.id, showLiveChat]);

  const handleSendMessage = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!inputMsg.trim() || !user || sending) return;

    const text = inputMsg;
    setInputMsg('');
    setSending(true);

    try {
      const res = await api.sendSupportMessage(user.id, text);
      if (res.success) {
        setMessages((prev) => [...prev, res.userMessage, res.agentMessage]);
      }
    } catch (err) {
      console.error('Failed to send support message:', err);
    } finally {
      setSending(false);
    }
  };

  const faqs = [
    {
      q: 'How does Win Go Color Prediction work?',
      a: 'Win Go runs continuous 1-minute, 3-minute, 5-minute, and 10-minute rounds. Players predict colors (Green, Red, Violet), Numbers (0-9), or Size (Big 5-9, Small 0-4). All rounds are settled on certified server logic with instant automatic payouts.',
    },
    {
      q: 'How long do recharges and withdrawals take?',
      a: 'USD Recharges via Credit/Debit Cards, PayPal, and USDT are credited automatically within 10-60 seconds. Withdrawals in USD (USDT TRC20 / Bank Wire) are processed 24/7 with average arrival time of 5-30 minutes directly to your bank account or crypto wallet.',
    },
    {
      q: 'What is the commission rate for inviting friends?',
      a: 'You receive up to 30% lifetime commission on all valid betting turnover generated by your invited members. Commissions are calculated and added directly to your wallet.',
    },
    {
      q: 'What are the rules for Green, Red, and Violet numbers?',
      a: 'Numbers 1, 3, 7, 9 are Green (2x). Numbers 2, 4, 6, 8 are Red (2x). Number 0 is Red + Violet (Red pays 1.5x, Violet pays 4.5x). Number 5 is Green + Violet (Green pays 1.5x, Violet pays 4.5x). Guessing the exact number pays 9x!',
    },
  ];

  return (
    <div id="customer-service-page" className="min-h-screen w-full bg-[#F6F7FB] pb-24 flex flex-col">
      <TopHeader
        variant="red"
        showBack={true}
        onBack={() => onNavigate('home')}
        title="Customer Service"
      />

      <div className="flex-1 px-4 py-4 space-y-4">
        {/* 24/7 Online Support Banner matching Screen 11 */}
        <div className="rounded-2xl p-6 bg-white border border-slate-100 shadow-sm flex flex-col items-center text-center">
          <div className="w-16 h-16 rounded-full bg-red-50 text-[#FA3534] flex items-center justify-center mb-3 shadow-inner">
            <Headphones className="w-9 h-9" />
          </div>
          <h2 className="text-base font-black text-slate-900">24/7 Online Support</h2>
          <p className="text-xs text-slate-500 mt-1 max-w-xs">
            We are here to help you with deposits, withdrawals, gaming rules, and VIP rewards anytime.
          </p>
        </div>

        {/* Contact Methods List matching Screen 11 */}
        <div className="bg-white rounded-2xl border border-slate-100 shadow-sm divide-y divide-slate-100 overflow-hidden">
          {/* Live Chat */}
          <button
            onClick={() => setShowLiveChat(true)}
            className="w-full p-4 flex items-center justify-between hover:bg-slate-50 transition-colors text-left group active:bg-slate-100"
          >
            <div className="flex items-center gap-3.5">
              <div className="w-10 h-10 rounded-xl bg-emerald-50 text-emerald-600 flex items-center justify-center group-hover:scale-105 transition-transform">
                <MessageSquare className="w-5 h-5" />
              </div>
              <div>
                <h4 className="text-xs font-bold text-slate-800">Live Chat</h4>
                <p className="text-[10px] text-slate-400">Chat directly with our support specialists</p>
              </div>
            </div>
            <ChevronRight className="w-4 h-4 text-slate-400 group-hover:translate-x-0.5 transition-transform" />
          </button>

          {/* Telegram */}
          <button
            onClick={() => window.open('https://t.me', '_blank')}
            className="w-full p-4 flex items-center justify-between hover:bg-slate-50 transition-colors text-left group active:bg-slate-100"
          >
            <div className="flex items-center gap-3.5">
              <div className="w-10 h-10 rounded-xl bg-sky-50 text-sky-600 flex items-center justify-center group-hover:scale-105 transition-transform">
                <Send className="w-5 h-5 ml-0.5" />
              </div>
              <div>
                <h4 className="text-xs font-bold text-slate-800">Telegram</h4>
                <p className="text-[10px] text-slate-400">Join our official VIP channel for signals</p>
              </div>
            </div>
            <ChevronRight className="w-4 h-4 text-slate-400 group-hover:translate-x-0.5 transition-transform" />
          </button>

          {/* WhatsApp */}
          <button
            onClick={() => window.open('https://api.whatsapp.com', '_blank')}
            className="w-full p-4 flex items-center justify-between hover:bg-slate-50 transition-colors text-left group active:bg-slate-100"
          >
            <div className="flex items-center gap-3.5">
              <div className="w-10 h-10 rounded-xl bg-green-50 text-green-600 flex items-center justify-center group-hover:scale-105 transition-transform">
                <MessageCircle className="w-5 h-5" />
              </div>
              <div>
                <h4 className="text-xs font-bold text-slate-800">WhatsApp</h4>
                <p className="text-[10px] text-slate-400">Message us on WhatsApp customer care</p>
              </div>
            </div>
            <ChevronRight className="w-4 h-4 text-slate-400 group-hover:translate-x-0.5 transition-transform" />
          </button>

          {/* Email */}
          <button
            onClick={() => {
              window.location.href = 'mailto:support@prismgame.com';
            }}
            className="w-full p-4 flex items-center justify-between hover:bg-slate-50 transition-colors text-left group active:bg-slate-100"
          >
            <div className="flex items-center gap-3.5">
              <div className="w-10 h-10 rounded-xl bg-amber-50 text-amber-600 flex items-center justify-center group-hover:scale-105 transition-transform">
                <Mail className="w-5 h-5" />
              </div>
              <div>
                <h4 className="text-xs font-bold text-slate-800">Email Support</h4>
                <p className="text-[10px] text-slate-400">support@prismgame.com</p>
              </div>
            </div>
            <ChevronRight className="w-4 h-4 text-slate-400 group-hover:translate-x-0.5 transition-transform" />
          </button>
        </div>

        {/* FAQ Section with accordion */}
        <div className="bg-white rounded-2xl p-4 border border-slate-100 shadow-sm">
          <div className="flex items-center gap-2 mb-3">
            <HelpCircle className="w-4 h-4 text-slate-500" />
            <h3 className="text-xs font-black text-slate-900 uppercase tracking-wider">
              Frequently Asked Questions
            </h3>
          </div>

          <div className="space-y-2">
            {faqs.map((f, idx) => {
              const isOpen = activeFaq === idx;
              return (
                <div key={idx} className="border border-slate-100 rounded-xl overflow-hidden">
                  <button
                    onClick={() => setActiveFaq(isOpen ? null : idx)}
                    className="w-full p-3 text-left font-bold text-xs text-slate-800 flex items-center justify-between hover:bg-slate-50"
                  >
                    <span>{f.q}</span>
                    <ChevronDown
                      className={`w-4 h-4 text-slate-400 transition-transform ${isOpen ? 'rotate-180 text-[#FA3534]' : ''}`}
                    />
                  </button>
                  {isOpen && (
                    <div className="p-3 pt-0 text-xs text-slate-600 leading-relaxed bg-slate-50/50">
                      {f.a}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        </div>
      </div>

      {/* Interactive Live Chat Modal Widget */}
      {showLiveChat && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-xs p-3">
          <div className="w-full max-w-sm h-[520px] bg-white rounded-2xl shadow-2xl flex flex-col overflow-hidden animate-scaleUp">
            {/* Chat Header */}
            <div className="bg-[#FA3534] text-white p-3.5 flex items-center justify-between">
              <div className="flex items-center gap-2.5">
                <div className="w-8 h-8 rounded-full bg-white/20 flex items-center justify-center">
                  <Headphones className="w-4 h-4" />
                </div>
                <div>
                  <h4 className="font-bold text-xs">Prism Support Specialist</h4>
                  <span className="text-[10px] text-green-200 flex items-center gap-1">
                    <span className="w-1.5 h-1.5 rounded-full bg-green-400 animate-pulse" />
                    Online 24/7
                  </span>
                </div>
              </div>
              <button
                onClick={() => setShowLiveChat(false)}
                className="p-1 hover:bg-white/10 rounded-full text-white/90"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            {/* Chat Messages */}
            <div className="flex-1 p-3.5 overflow-y-auto space-y-3 bg-[#F8F9FD]">
              {messages.map((m) => {
                const isUser = m.sender === 'user';
                return (
                  <div
                    key={m.id}
                    className={`flex flex-col ${isUser ? 'items-end' : 'items-start'}`}
                  >
                    <div
                      className={`max-w-[82%] p-2.5 rounded-2xl text-xs ${
                        isUser
                          ? 'bg-[#FA3534] text-white rounded-tr-none'
                          : 'bg-white text-slate-800 rounded-tl-none shadow-xs border border-slate-100'
                      }`}
                    >
                      {m.message}
                    </div>
                    <span className="text-[9px] text-slate-400 mt-0.5 px-1 font-mono">
                      {new Date(m.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                    </span>
                  </div>
                );
              })}
              {sending && (
                <div className="text-[10px] text-slate-400 italic">Prism agent is typing...</div>
              )}
            </div>

            {/* Chat Input */}
            <form onSubmit={handleSendMessage} className="p-2.5 bg-white border-t border-slate-100 flex items-center gap-2">
              <input
                type="text"
                value={inputMsg}
                onChange={(e) => setInputMsg(e.target.value)}
                placeholder="Type your question..."
                className="flex-1 text-xs p-2.5 border border-slate-200 rounded-xl bg-slate-50 focus:bg-white focus:border-[#FA3534] outline-none"
              />
              <button
                type="submit"
                disabled={!inputMsg.trim() || sending}
                className="p-2.5 bg-[#FA3534] text-white rounded-xl disabled:opacity-50 active:scale-95 transition-all shadow-sm"
              >
                <Send className="w-4 h-4" />
              </button>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
